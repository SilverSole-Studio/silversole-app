"""Writes lib/shared/widgets/town_icons_data.dart from the game's own icon set
(lw-integrate/engine/icons.js: our own art, 24x24, brown #3b3325 outline, flat
fills). Only the icons the app draws are copied.

Run: python -I tool/make_town_icons.py [path to icons.js]
"""
import pathlib
import re
import sys

SRC = pathlib.Path(
    sys.argv[1] if len(sys.argv) > 1 else "C:/Users/Admin/dev/lw-integrate/engine/icons.js"
)
OUT = pathlib.Path(__file__).resolve().parent.parent / "lib/shared/widgets/town_icons_data.dart"
WANT = [
    "sun", "starO", "map", "ball", "clipboard", "person", "target", "flag", "check",
    "go", "lock", "gear", "shoe", "heart", "shield", "coin", "star", "warn",
    "book", "gift", "flame", "calendar", "trophy", "medal", "leaf", "drop",
    "bulb", "cross", "spark", "bike", "train", "pause", "cloud", "party",
]

text = SRC.read_text(encoding="utf-8")
start = text.index("var D = {")
block = text[start:]
K = "#3b3325"
found = {}
for name in WANT:
    m = re.search(r"^\s{4}" + name + r": (.*?),?\s*$", block, re.M)
    if not m:
        print("missing", name, file=sys.stderr)
        continue
    expr = m.group(1).rstrip(",")
    # Evaluate the JS string concatenation: 'a' + K + 'b'
    parts = re.findall(r"'([^']*)'|(K)", expr)
    out = ""
    for lit, k in parts:
        out += K if k else lit
    found[name] = out

lines = [
    "// GENERATED by tool/make_town_icons.py from the game's engine/icons.js.",
    "// Our own art: 24x24, brown outline, flat fills. Do not edit by hand.",
    "",
    "/// SVG fragments (inside a 24x24 `<g>` that sets the outline), by name.",
    "const Map<String, String> kTownIconPaths = {",
]
for name, svg in found.items():
    assert "'''" not in svg
    lines.append(f"  '{name}': r'''{svg}''',")
lines.append("};")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote", OUT, len(found), "icons", file=sys.stderr)
